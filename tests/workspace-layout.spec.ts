import { expect, test } from '@playwright/test';

test('menus and export results do not resize the canvas; closing and reopening keeps the batch', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Minecraft GUI Maker' })).toBeVisible();
  const host = page.getByTestId('canvas-host');
  const before = (await host.boundingBox())!;
  expect(before.height).toBeGreaterThan(600);
  await page.getByText('设计区与游戏 GUI Scale', { exact: false }).first().click();
  await expect(page.getByLabel('设计区宽', { exact: true })).toBeVisible();
  expect((await host.boundingBox())!.height).toBe(before.height);
  await page.getByText('设计区与游戏 GUI Scale', { exact: false }).first().click();
  await page.getByTestId('save-status').click();
  await expect(page.getByRole('button', { name: '立即保存' })).toBeVisible();
  expect((await host.boundingBox())!.height).toBe(before.height);
  await page.getByTestId('save-status').click();
  await page.getByRole('button', { name: '导出规格', exact: true }).click();
  await expect(page.locator('.export-links a')).toHaveCount(6);
  const reference = await page.getByTestId('export-reference').textContent();
  expect((await host.boundingBox())!.height).toBe(before.height);
  await page.getByRole('button', { name: '关闭导出结果' }).click();
  await expect(page.getByTestId('export-panel')).toHaveCount(0);
  await page.getByRole('button', { name: '查看导出结果' }).click();
  await expect(page.getByTestId('export-reference')).toHaveText(reference!);
  await expect(page.locator('.export-links a')).toHaveCount(6);
  expect((await host.boundingBox())!.height).toBe(before.height);
  await page.getByRole('button', { name: '关闭导出结果' }).click();
  await page.getByRole('button', { name: '收起组件栏' }).click();
  await page.getByRole('button', { name: '收起属性栏' }).click();
  await expect.poll(async () => (await host.boundingBox())!.width).toBeGreaterThan(before.width + 400);
  await page.getByRole('button', { name: '展开组件栏' }).click();
  await page.getByRole('button', { name: '展开属性栏' }).click();
  await expect(page.getByRole('button', { name: '添加 Button', exact: true })).toBeVisible();
  await expect.poll(async () => (await host.boundingBox())!.width).toBe(before.width);
});
