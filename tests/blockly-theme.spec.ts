import { test, expect, type Page } from '@playwright/test';
import { genericBehaviorProject } from './fixtures/genericBehaviorProject';
async function setup(page: Page) { page.on('dialog', d => d.accept()); await page.emulateMedia({ colorScheme: 'light' }); await page.goto('/'); await page.getByLabel('导入项目文件').setInputFiles({ name: 'blk-theme.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(genericBehaviorProject())) }); await expect(page.locator('.statusbar [role=status]')).toContainText('导入成功'); await page.getByRole('button', { name: 'Blockly 实验', exact: true }).click(); await page.getByLabel('Blockly 规则').selectOption('rule_generic_number'); await expect(page.getByTestId('blockly-diagnostic')).toContainText('与项目一致'); await page.evaluate(async () => { const url = performance.getEntriesByType('resource').map(e => e.name).find(n => n.includes('/blockly_core.js?'))!; const b = await import(url), w = window as any; w.__blk = b; w.__ws = b.common.getMainWorkspace(); w.__injection = w.__ws.getInjectionDiv(); }); }
async function theme(page: Page, name: '浅色' | '深色' | '跟随系统') { await page.getByRole('navigation', { name: '编辑器菜单' }).getByText('视图', { exact: true }).click(); await page.getByRole('button', { name: `主题：${name}`, exact: true }).click(); if (name !== '跟随系统')
    await expect.poll(async () => (await state(page)).theme).toBe(name === '深色' ? 'gui-maker-dark' : 'gui-maker-light'); }
async function state(page: Page) { return page.evaluate(() => { const w = window as any, b = w.__blk, ws = b.common.getMainWorkspace(); return { state: b.serialization.workspaces.save(ws), id: ws.id, same: ws === w.__ws && ws.getInjectionDiv() === w.__injection, undo: ws.getUndoStack().length, redo: ws.getRedoStack().length, selected: b.common.getSelected()?.id ?? null, theme: ws.getTheme().name, background: getComputedStyle(ws.getInjectionDiv().querySelector('.blocklySvg')).backgroundColor, flyout: getComputedStyle(document.querySelector('.blocklyFlyoutBackground')!).fill }; }); }
test('BLK-1 real workspace switches Light Dark System without reinjection, semantic edits, history or draft loss', async ({ page }, info) => {
    await setup(page);
    const authority = await page.getByTestId('project-json').textContent();
    await theme(page, '浅色');
    await expect.poll(async () => (await state(page)).theme).toBe('gui-maker-light');
    const initial = await state(page);
    await expect(page.getByRole('button', { name: '保存积木规则' })).toBeDisabled();
    await theme(page, '深色');
    const dark = await state(page);
    expect(dark.state).toEqual(initial.state);
    expect(dark.id).toBe(initial.id);
    expect(dark.same).toBe(true);
    expect(dark.undo).toBe(initial.undo);
    expect(dark.background).not.toBe(initial.background);
    expect(dark.flyout).not.toBe(initial.flyout);
    await expect(page.getByRole('button', { name: '保存积木规则' })).toBeDisabled();
    await page.evaluate(() => { const w = window as any, blocks = w.__ws.getAllBlocks(false); blocks.find((b: any) => b.type === 'gui_constant').setFieldValue(6, 'VALUE'); });
    await expect(page.getByTestId('blockly-diagnostic')).toContainText('未保存草稿');
    const dirty = await state(page);
    await theme(page, '浅色');
    expect((await state(page)).state).toEqual(dirty.state);
    await expect(page.getByTestId('blockly-diagnostic')).toContainText('未保存草稿');
    await theme(page, '跟随系统');
    await page.evaluate(() => { const w = window as any; w.__blk.getFocusManager().focusNode(w.__ws.getTopBlocks(false)[0]); });
    const selected = await state(page);
    expect(selected.selected).not.toBeNull();
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect.poll(async () => (await state(page)).theme).toBe('gui-maker-dark');
    expect((await state(page)).selected).toBe(selected.selected);
    expect((await state(page)).state).toEqual(dirty.state);
    expect((await state(page)).same).toBe(true);
    await page.getByRole('button', { name: 'GUI 设计模式' }).click();
    await theme(page, '浅色');
    await page.getByRole('button', { name: 'Blockly 实验', exact: true }).click();
    expect((await state(page)).theme).toBe('gui-maker-light');
    expect((await state(page)).state).toEqual(dirty.state);
    expect((await state(page)).same).toBe(true);
    expect(await page.getByTestId('project-json').textContent()).toBe(authority);
    await page.evaluate(() => (window as any).__ws.scrollCenter());
    await page.screenshot({ path: info.outputPath('blockly-light.png'), animations: 'disabled' });
    await theme(page, '深色');
    await page.screenshot({ path: info.outputPath('blockly-dark.png'), animations: 'disabled' });
});
test('BLK-1 body dropdown and tooltip use the resolved palette; unconfirmed options are not committed', async ({ page }, info) => {
    await setup(page);
    await theme(page, '跟随系统');
    const before = await state(page);
    const field = page.locator('.blocklySvg .blocklyBlockCanvas [data-block-type="gui_on_event"] > .blocklyDropdownField').first();
    await field.click();
    const dropdown = page.locator('.blocklyDropDownDiv');
    await expect(dropdown).toBeVisible();
    expect(await dropdown.evaluate(e => getComputedStyle(e).backgroundColor)).toBe('rgb(255, 255, 255)');
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect.poll(async () => (await state(page)).theme).toBe('gui-maker-dark');
    await expect(dropdown).toBeHidden();
    expect((await state(page)).state).toEqual(before.state);
    await field.click();
    await expect(dropdown).toBeVisible();
    expect(await dropdown.evaluate(e => getComputedStyle(e).backgroundColor)).toBe('rgb(52, 61, 73)');
    expect(await dropdown.locator('.blocklyMenuItemContent').first().evaluate(e => getComputedStyle(e).color)).toBe('rgb(222, 230, 242)');
    await expect(dropdown).toHaveCSS('opacity', '1');
    await page.screenshot({ path: info.outputPath('dropdown-dark.png'), animations: 'disabled' });
    await page.keyboard.press('Escape');
    await page.locator('.blocklySvg .blocklyBlockCanvas [data-block-type="gui_on_event"] > .blocklyPath').first().hover({ position: { x: 20, y: 10 } });
    const tooltip = page.locator('.gui-maker-blockly-ui.blocklyTooltipDiv');
    await expect(tooltip).toBeVisible({ timeout: 4000 });
    expect(await tooltip.evaluate(e => getComputedStyle(e).backgroundColor)).toBe('rgb(48, 58, 70)');
    expect((await state(page)).state).toEqual(before.state);
});
test('BLK-1 System change keeps a live field editor and Escape cancellation; applies pending Theme after close', async ({ page }) => {
    await setup(page);
    await theme(page, '跟随系统');
    const before = await state(page);
    await page.evaluate(() => { const w = window as any, b = w.__ws.getAllBlocks(false).find((b: any) => b.type === 'gui_constant'); b.getField('VALUE').getSvgRoot().setAttribute('data-testid', 'live-value-field'); });
    await page.getByTestId('live-value-field').click();
    const input = page.locator('.gui-maker-blockly-ui .blocklyHtmlInput');
    await expect(input).toBeVisible();
    await input.fill('9');
    const editing = await state(page);
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await expect(input).toBeFocused();
    await expect(input).toHaveValue('9');
    expect((await state(page)).state).toEqual(editing.state);
    expect((await state(page)).theme).toBe('gui-maker-light');
    await expect.poll(() => input.evaluate(e => getComputedStyle(e).backgroundColor)).toBe('rgb(26, 32, 40)');
    await input.press('Escape');
    await expect(input).toBeHidden();
    await expect.poll(async () => (await state(page)).theme).toBe('gui-maker-dark');
    expect((await state(page)).state).toEqual(before.state);
    expect((await state(page)).same).toBe(true);
});
