import { expect, test } from '@playwright/test';
import { emptyProject } from '../src/domain/model';
import { showScreenControls } from './workspace-helpers';

test('H1 user flow creates, edits, versions, exports, imports and restores', async ({ page }) => {
  await page.goto('/');
  const old = emptyProject(); old.schemaVersion = '0.3.0';
  await page.getByLabel('导入项目文件').setInputFiles({ name: 'old.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(old)) });
  await expect(page.locator('.statusbar [role="status"]')).toContainText('导入成功');
  await page.getByRole('button', { name: '添加 Checkbox' }).click();
  await showScreenControls(page); await page.keyboard.press('Control+z');
  let doc = JSON.parse((await page.getByTestId('project-json').textContent())!);
  expect(doc.schemaVersion).toBe('0.3.0'); expect(doc.screens[0].nodes).toHaveLength(0);
  await page.keyboard.press('Control+Shift+z');
  doc = JSON.parse((await page.getByTestId('project-json').textContent())!);
  expect(doc.schemaVersion).toBe('0.4.0'); expect(doc.screens[0].nodes).toHaveLength(1);
  await page.getByRole('button', { name: '选择 node_1' }).click();
  await expect(page.getByLabel('构造最大宽度')).toHaveValue('120');
  await expect(page.getByLabel('文字阴影')).not.toBeChecked();
  await page.getByLabel('X', { exact: true }).fill('40'); await page.getByLabel('X', { exact: true }).press('Enter');
  await page.getByLabel('复选框文字', { exact: true }).fill('Enable feature');
  await page.getByLabel('复选框文字', { exact: true }).press('Enter');
  await page.getByLabel('初始勾选').check();
  const read = async () => JSON.parse((await page.getByTestId('project-json').textContent())!);
  doc = await read(); expect(doc.schemaVersion).toBe('0.4.0'); expect(doc.screens[0].nodes[0].props.selected).toBe(true); expect(doc.screens[0].nodes[0].bounds.x).toBe(40);
  await page.getByRole('button', { name: '添加 CycleButton' }).click();
  await page.getByLabel('选项名称', { exact: true }).fill('Mode'); await page.getByLabel('选项名称', { exact: true }).press('Enter');
  await page.getByLabel('显示格式').selectOption('value-only');
  doc = await read(); expect(doc.screens[0].nodes).toHaveLength(2); expect(doc.screens[0].nodes[1].props.name.value).toBe('Mode');
  const before = JSON.stringify(doc); await showScreenControls(page);
  await expect(page.getByTestId('save-status')).toContainText('已保存');
  await page.reload(); await expect(page.getByTestId('project-json')).toContainText('minecraft:cycle-button');
  expect(JSON.stringify(await read())).toBe(before);
  await page.getByRole('button', { name: '导出规格', exact: true }).click();
  await expect(page.locator('.export-links a')).toHaveCount(6);
  await expect(page.getByTestId('export-panel')).toContainText('文字阴影按各组件的设计设置输出');
  const png = await page.locator('.export-links a').nth(1).evaluate(async a => { const b = await createImageBitmap(await (await fetch((a as HTMLAnchorElement).href)).blob()); const size = [b.width, b.height]; b.close(); return size; });
  expect(png).toEqual([320, 180]);
  await page.getByRole('button', { name: '关闭导出结果' }).click();
  const bad = structuredClone(doc); bad.schemaVersion = '0.3.0';
  await page.getByLabel('导入项目文件').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bad)) });
  await expect(page.locator('.statusbar [role="alert"]')).toContainText('导入失败');
  expect(JSON.stringify(await read())).toBe(before);
  await page.getByLabel('导入项目文件').setInputFiles({ name: 'good.json', mimeType: 'application/json', buffer: Buffer.from(before) });
  await expect(page.locator('.statusbar [role="status"]')).toContainText('导入成功');
  expect(JSON.stringify(await read())).toBe(before);
});

test('checkbox and initial cycle option can be edited directly on canvas', async ({ page }) => {
  await page.goto('/');
  const host = page.getByTestId('canvas-host');
  const point = async (x: number, y: number) => host.evaluate((el, p) => { const r = el.getBoundingClientRect(), z = Number(el.getAttribute('data-zoom')); return { x: r.x + Number(el.getAttribute('data-origin-x')) + p.x * z, y: r.y + Number(el.getAttribute('data-origin-y')) + p.y * z }; }, { x, y });
  await page.getByRole('button', { name: '添加 Checkbox' }).click();
  let p = await point(25, 24); await page.mouse.dblclick(p.x, p.y);
  await page.getByLabel('画布文字编辑').fill('Enabled'); await page.getByLabel('画布文字编辑').press('Enter');
  let doc = JSON.parse((await page.getByTestId('project-json').textContent())!);
  expect(doc.screens[0].nodes[0].props.message.value).toBe('Enabled');
  await page.getByRole('button', { name: '添加 CycleButton' }).click();
  p = await point(50, 45); await page.mouse.dblclick(p.x, p.y);
  await expect(page.locator('.inline-editor-help')).toContainText('初始选项');
  await page.getByLabel('画布文字编辑').fill('First choice'); await page.getByLabel('画布文字编辑').press('Enter');
  doc = JSON.parse((await page.getByTestId('project-json').textContent())!);
  expect(doc.screens[0].nodes[1].props.options[0].text.value).toBe('First choice');
});
